BEGIN;

-- Franchise history (Part 3): transactions, draft picks and swaps, salaries,
-- contracts, coaches, executives and honors.
--
-- Filled by a local import (scripts/import-franchise-history.ts), not by the
-- nightly pipeline. Every row has a deterministic natural key so page URLs
-- survive re-imports. Unknown facts are NULL, never 0 or a default.
-- Franchise columns hold nba_franchise_id values (as team_seasons does).
--
-- Backward compatible: only adds tables; nothing existing changes.
-- Idempotent; safe to re-run.

CREATE TABLE IF NOT EXISTS person_xref (
  person_key     TEXT PRIMARY KEY,          -- bbref id, 'nba:<personId>' or 'name:<normalized>-<year>'
  kind           TEXT NOT NULL CHECK (kind IN ('player','coach','executive')),
  display_name   TEXT NOT NULL,
  birthdate      DATE,
  nba_person_id  INTEGER,
  player_id      BIGINT REFERENCES players(player_id)
);

CREATE TABLE IF NOT EXISTS draft_picks (
  pick_id                  SERIAL PRIMARY KEY,
  pick_key                 TEXT NOT NULL UNIQUE,     -- year-round-original_franchise
  draft_year               SMALLINT NOT NULL,
  round                    SMALLINT NOT NULL,
  original_franchise_id    INTEGER NOT NULL,
  protections              JSONB,                    -- [{ year, range, then }]
  protections_text         TEXT,
  protections_known        BOOLEAN,                  -- NULL/false = not recorded, never "unprotected"
  status                   TEXT CHECK (status IN ('future','used','conveyed_as_other','extinguished','forfeited')),
  overall_pick             SMALLINT,
  selected_person          TEXT REFERENCES person_xref(person_key) ON UPDATE CASCADE,
  final_owner_franchise_id INTEGER
);
CREATE INDEX IF NOT EXISTS idx_draft_picks_year ON draft_picks (draft_year);

CREATE TABLE IF NOT EXISTS pick_swaps (
  swap_id            SERIAL PRIMARY KEY,
  swap_key           TEXT NOT NULL UNIQUE,
  draft_year         SMALLINT NOT NULL,
  round              SMALLINT NOT NULL,
  franchise_a        INTEGER NOT NULL,
  franchise_b        INTEGER NOT NULL,
  protections        JSONB,
  protections_text   TEXT,
  protections_known  BOOLEAN,
  exercised          BOOLEAN                         -- NULL until the draft
);

CREATE TABLE IF NOT EXISTS transactions (
  transaction_id     BIGSERIAL PRIMARY KEY,
  transaction_key    TEXT NOT NULL UNIQUE,           -- first source key, e.g. 'nba:Trade 1158000'
  slug               TEXT NOT NULL UNIQUE,
  date               DATE,
  season_id          SMALLINT,
  involves_clippers  BOOLEAN NOT NULL,
  kind               TEXT NOT NULL,
  description        TEXT NOT NULL,                  -- generated by us, never source prose
  sources            TEXT[] NOT NULL,
  is_complete        BOOLEAN NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_transactions_date ON transactions (date);
CREATE INDEX IF NOT EXISTS idx_transactions_clippers_date ON transactions (involves_clippers, date);

CREATE TABLE IF NOT EXISTS transaction_parts (
  part_id            BIGSERIAL PRIMARY KEY,
  transaction_id     BIGINT NOT NULL REFERENCES transactions(transaction_id) ON UPDATE CASCADE ON DELETE CASCADE,
  from_franchise_id  INTEGER,
  to_franchise_id    INTEGER,                        -- NULL for signings and waivers (free agency)
  asset_kind         TEXT NOT NULL CHECK (asset_kind IN ('player','draft_rights','pick','swap','cash','exception','other')),
  person_key         TEXT REFERENCES person_xref(person_key) ON UPDATE CASCADE,
  pick_id            INTEGER REFERENCES draft_picks(pick_id) ON UPDATE CASCADE,
  swap_id            INTEGER REFERENCES pick_swaps(swap_id) ON UPDATE CASCADE,
  unlinked_text      TEXT,
  gap_reason         TEXT CHECK (gap_reason IN ('pick_unidentified','protections_unknown','source_conflict','person_unmatched'))
);
CREATE INDEX IF NOT EXISTS idx_transaction_parts_txn ON transaction_parts (transaction_id);
CREATE INDEX IF NOT EXISTS idx_transaction_parts_person ON transaction_parts (person_key);
CREATE INDEX IF NOT EXISTS idx_transaction_parts_pick ON transaction_parts (pick_id);

CREATE TABLE IF NOT EXISTS draft_lottery (
  draft_year       SMALLINT NOT NULL,
  pick_id          INTEGER NOT NULL REFERENCES draft_picks(pick_id) ON UPDATE CASCADE,
  pre_lottery_slot SMALLINT,
  odds_first       NUMERIC(6,3),
  pick_won         SMALLINT,
  tie_unresolved   BOOLEAN,
  source           TEXT NOT NULL CHECK (source IN ('wiki','derived')),
  PRIMARY KEY (draft_year, pick_id)
);

CREATE TABLE IF NOT EXISTS salaries (
  season_id   SMALLINT NOT NULL,
  person_key  TEXT NOT NULL REFERENCES person_xref(person_key) ON UPDATE CASCADE,
  amount_usd  BIGINT,
  source      TEXT NOT NULL,
  UNIQUE (season_id, person_key)
);

CREATE TABLE IF NOT EXISTS payroll_seasons (
  season_id         SMALLINT PRIMARY KEY,
  listed_players    SMALLINT,
  roster_players    SMALLINT,
  listed_total_usd  BIGINT,
  is_partial        BOOLEAN
);

CREATE TABLE IF NOT EXISTS contracts (
  snapshot_id    TEXT NOT NULL,                      -- one per weekly refresh; the newest is active
  person_key     TEXT NOT NULL REFERENCES person_xref(person_key) ON UPDATE CASCADE,
  season_id      SMALLINT NOT NULL,
  amount_usd     BIGINT,
  guaranteed_usd BIGINT,
  option         TEXT CHECK (option IN ('player','team','early_termination')),
  fetched_at     TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (snapshot_id, person_key, season_id)
);
CREATE INDEX IF NOT EXISTS idx_contracts_fetched ON contracts (fetched_at DESC);

CREATE TABLE IF NOT EXISTS coach_seasons (
  season_id       SMALLINT NOT NULL,
  person_key      TEXT NOT NULL REFERENCES person_xref(person_key) ON UPDATE CASCADE,
  ordinal         SMALLINT NOT NULL,                 -- order within a season (mid-season changes)
  games           SMALLINT,
  wins            SMALLINT,
  losses          SMALLINT,
  playoff_wins    SMALLINT,
  playoff_losses  SMALLINT,
  PRIMARY KEY (season_id, person_key, ordinal)
);

CREATE TABLE IF NOT EXISTS executive_terms (
  term_id     SERIAL PRIMARY KEY,
  person_key  TEXT NOT NULL REFERENCES person_xref(person_key) ON UPDATE CASCADE,
  title       TEXT,
  start_date  DATE,
  end_date    DATE
);

CREATE TABLE IF NOT EXISTS honors (
  honor_id    SERIAL PRIMARY KEY,
  season_id   SMALLINT,                              -- NULL for retired numbers
  person_key  TEXT NOT NULL REFERENCES person_xref(person_key) ON UPDATE CASCADE,
  honor       TEXT NOT NULL,
  detail      TEXT
);

COMMIT;
