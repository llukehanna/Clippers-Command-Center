// worker.ts — Cloudflare Worker entry (wrangler.jsonc "main").
// Wraps the OpenNext worker that `opennextjs-cloudflare build` writes to
// .open-next/worker.js with what Vercel used to do at its edge, in order:
//
// 1. Host redirects (formerly vercel.json): the old ccc.lukeghanna.com name
//    301s to the canonical clippers.lukeghanna.com, path and query kept.
// 2. Crawlers that ignore robots.txt are refused (src/lib/bot-guard.ts),
//    which the Vercel Firewall used to do.
// 3. Legacy query-string URLs 301 to their path-based pages, and any /api/*
//    outside the live/media allowlist is a 404 (src/lib/legacy-redirect.ts),
//    so only the live pipeline reaches the database through the API.
// 4. A shared edge cache (src/lib/edge-cache.ts): prerendered pages (a day,
//    next.config.ts), /api/media and /api/live (its own 2 s / 30 s) declare a
//    TTL with CDN-Cache-Control, and hits are served from the Cache API
//    without running OpenNext, so a page's prerender cache entry isn't read
//    and parsed per request. The Cache API only works on a custom domain; on workers.dev
//    every lookup misses and every request renders. Old-season /schedule/<id>
//    pages (not prerendered) 302 to /history/<id> from the cache's response.

// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore -- generated by `opennextjs-cloudflare build`; absent before the first build
import { default as openNext } from './.open-next/worker.js'
import { serveWithEdgeCache, type EdgeCacheStore, type WaitUntil } from './src/lib/edge-cache'
import { blockedReason, blockedResponse } from './src/lib/bot-guard'
import { apiBlocked, legacyRedirect, scheduleFallback } from './src/lib/legacy-redirect'

interface OpenNextWorker {
  fetch(request: Request, env: unknown, ctx: WaitUntil): Promise<Response>
}

const app = openNext as OpenNextWorker

const CANONICAL_ORIGIN = 'https://clippers.lukeghanna.com'
const REDIRECT_HOSTS = new Set(['ccc.lukeghanna.com'])

const worker = {
  async fetch(request: Request, env: { CF_VERSION_METADATA?: { id?: string } }, ctx: WaitUntil): Promise<Response> {
    const url = new URL(request.url)
    if (REDIRECT_HOSTS.has(url.hostname)) {
      return Response.redirect(`${CANONICAL_ORIGIN}${url.pathname}${url.search}`, 301)
    }
    // Crawlers that ignore robots.txt are refused before Next.js runs (src/lib/bot-guard.ts).
    if (blockedReason(request)) return blockedResponse()
    // Old query-string URLs 301 to their path-based pages (src/lib/legacy-redirect.ts).
    if (request.method === 'GET' || request.method === 'HEAD') {
      const to = legacyRedirect(url)
      if (to) return Response.redirect(new URL(to, url).toString(), 301)
    }
    // Only the live pipeline and media reach the database; other /api/* are gone.
    if (apiBlocked(url.pathname)) {
      return new Response('Not found', { status: 404, headers: { 'cache-control': 'no-store' } })
    }
    const store = (caches as unknown as { default: EdgeCacheStore }).default
    const version = env.CF_VERSION_METADATA?.id
    const response = await serveWithEdgeCache(request, () => app.fetch(request, env, ctx), { store, ctx, version })
    // Old-season schedule pages aren't prerendered; send them to History.
    const fallback = scheduleFallback(url, response.status)
    if (fallback) return Response.redirect(new URL(fallback.location, url).toString(), fallback.status)
    return response
  },
}

export default worker
